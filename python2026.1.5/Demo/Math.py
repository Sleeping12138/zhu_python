# 写一个计算方法类
class Math:
    @staticmethod
    def add(a, b):
        return a + b

    @staticmethod
    def sub(a, b):
        return a - b

    @staticmethod
    def mul(a, b):
        return a * b

    @staticmethod
    def div(a, b):
        return a / b

    @staticmethod
    def mod(a, b):
        return a % b

    @staticmethod
    def pow(a, b):
        return a ** b
